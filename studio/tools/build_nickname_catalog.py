# -*- coding: utf-8 -*-
"""Regenerate the nickname catalog from the authored SMILES table.

Input : studio/nicknames.src.json   (name -> {smiles, confidence, note})
Output: studio/nickname_catalog.hpp (compiled into the editor, namespace nickdata)
        studio/nicknames.json       (CDXML fragments for the Python backend)
        studio/tools/generation_report.json

The structures are laid out by RDKit from SMILES we authored. No third-party
fragment coordinates or ids are used. Run with the bundled Python:
    python -B re_round62_viewer/studio/tools/build_nickname_catalog.py
"""
import json, sys
from pathlib import Path
from rdkit import Chem
from rdkit.Chem import rdDepictor, rdMolDescriptors
import xml.etree.ElementTree as ET

STUDIO = Path(__file__).resolve().parents[1]

def fragment_xml(mol):
    rdDepictor.Compute2DCoords(mol)
    Chem.Kekulize(mol, clearAromaticFlags=True)
    frag = ET.Element("fragment", {"id": "1"})
    for a in mol.GetAtoms():
        pos = mol.GetConformer().GetAtomPosition(a.GetIdx())
        attrs = {"id": str(a.GetIdx()+2), "p": "%.2f %.2f" % (pos.x*30, -pos.y*30)}
        if not a.GetAtomicNum():
            attrs["NodeType"] = "ExternalConnectionPoint"
        else:
            attrs.update({"Element": str(a.GetAtomicNum()), "NumHydrogens": str(a.GetTotalNumHs())})
            if a.GetFormalCharge():
                attrs["Charge"] = str(a.GetFormalCharge())
        ET.SubElement(frag, "n", attrs)
    for b in mol.GetBonds():
        ET.SubElement(frag, "b", {"id": str(mol.GetNumAtoms()+2+b.GetIdx()),
                                  "B": str(b.GetBeginAtomIdx()+2), "E": str(b.GetEndAtomIdx()+2),
                                  "Order": str(int(b.GetBondTypeAsDouble()))})
    return ET.tostring(frag, encoding="unicode")

def build(entries):
    out, report, bad = {}, {}, []
    for name, rec in sorted(entries.items()):
        smiles = rec.get("smiles") if isinstance(rec, dict) else None
        if not smiles:
            bad.append((name, "no smiles")); continue
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            bad.append((name, "invalid smiles")); continue
        if rec.get("standalone"):
            bad.append((name, "standalone molecule not supported by the editor")); continue
        dummies = [a for a in mol.GetAtoms() if a.GetAtomicNum() == 0]
        if len(dummies) != 1:
            bad.append((name, "%d dummy atoms" % len(dummies))); continue
        out[name] = fragment_xml(Chem.Mol(mol))
        formula_mol = Chem.RWMol(mol)
        for a in sorted([a.GetIdx() for a in mol.GetAtoms() if a.GetAtomicNum() == 0], reverse=True):
            formula_mol.RemoveAtom(a)
        formula = rdMolDescriptors.CalcMolFormula(formula_mol.GetMol()) if formula_mol.GetNumAtoms() else ""
        report[name] = {"atoms": mol.GetNumAtoms(), "bonds": mol.GetNumBonds(), "formula": formula,
                        "confidence": rec.get("confidence", ""), "note": rec.get("note", "")}
    return out, report, bad

def emit_cpp(entries, report):
    lines = ['#pragma once',
             '// Generated by tools/build_nickname_catalog.py. Do not edit by hand.',
             '// Structures are authored in studio/nicknames.src.json and laid out by RDKit.',
             '#include <string>',
             'namespace nickdata {',
             'struct Entry {const char* name; const char* fragment; const char* formula;};',
             'static const Entry nicknames[]={']
    for name in sorted(entries):
        lines.append('{"%s",R"NICK(%s)NICK","%s"},' % (name, entries[name], report[name]["formula"]))
    lines += ['};',
              'inline const Entry* find(const std::string& n){for(const auto& v:nicknames)if(n==v.name)return &v;return nullptr;}',
              'inline const Entry* findAlias(const std::string& n){return find(n);}',
              '}']
    return "\n".join(lines) + "\n"

def main(argv):
    source = Path(argv[1]) if len(argv) > 1 else STUDIO/"nicknames.src.json"
    entries = json.loads(source.read_text(encoding="utf-8"))
    out, report, bad = build(entries)
    (STUDIO/"nickname_catalog.hpp").write_text(emit_cpp(out, report), encoding="utf-8")
    (STUDIO/"nicknames.json").write_text(json.dumps(out, ensure_ascii=False, indent=0, sort_keys=True), encoding="utf-8")
    rep = {"source": str(source.name), "count": len(out), "rejected": bad, "entries": report}
    (STUDIO/"tools/generation_report.json").write_text(json.dumps(rep, ensure_ascii=False, indent=1), encoding="utf-8")
    print("generated", len(out), "entries; rejected", len(bad))
    return 0

if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
